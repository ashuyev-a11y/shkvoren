/**
 * Знак ШКВОРЕНЬ — «README (3).md», раздел «Логотип».
 *
 * Шестигранная гайка, через которую проходит шкворень: жёлтая гайка
 * (`signal`), графитовый шкворень (`graphite`). Файлов `shkvoren-mark.svg`
 * и `shkvoren-mark-mono.svg` в проекте нет — в `design-system.json`
 * группа Logos описана, но `blobs` пуст. Поэтому знак собран разметкой
 * по текстовому описанию брендбука, а не скопирован из макета.
 *
 * Геометрия выбрана так, чтобы правила брендбука выполнялись буквально:
 * гайка развёрнута плоскими гранями вверх и вниз, шкворень проходит по
 * вертикали и упирается в эти грани — он читается как проходящий сквозь
 * гайку и при этом не выходит за её силуэт. Последнее важно: на шапке
 * фон graphite, и вылет шкворня за гайку был бы невидим.
 *
 * Размер задаётся в `em` от кегля вордмарка: высота знака равна высоте
 * прописных × 1,4, а у Unbounded высота прописных ≈ 0,72em, что даёт
 * ровно 1em. При кегле `t-title` (26px) знак выходит 26px — выше
 * минимальных 24px из брендбука.
 *
 * Одноцветный вариант брендбук требует только для жёлтого фона. Логотип
 * на жёлтом фоне в проекте нигде не стоит, поэтому второй вариант не
 * заводится: он был бы кодом без применения.
 */
export function LogoMark() {
  // Гайка: шестигранник с плоскими верхней и нижней гранями.
  const nut = '6.5,2 17.5,2 23,12 17.5,22 6.5,22 1,12';

  return (
    <svg
      viewBox="0 0 24 24"
      // Знак декоративный: рядом стоит слово «ШКВОРЕНЬ», и озвучивать
      // название дважды скринридеру не нужно.
      aria-hidden="true"
      focusable="false"
      style={{ width: '1em', height: '1em', flex: 'none' }}
    >
      <polygon points={nut} fill="var(--signal)" />

      {/* Шкворень проходит сквозь гайку по вертикали */}
      <rect x="9.5" y="2" width="5" height="20" rx="1" fill="var(--graphite)" />
    </svg>
  );
}
