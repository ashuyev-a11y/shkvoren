/**
 * Типы заказа — контракт из docs/data-model.md §8 и docs/technical-spec.md §6.
 *
 * Заказ существует с момента записи строки в лист «Заказы» (решение 2).
 * Всё, что до записи, — черновик в браузере.
 */

/** Позиция корзины в том виде, в котором её присылает браузер. */
export type OrderDraftItem = {
  /** Ключ позиции — колонка ID таблицы. */
  id: number;
  /** Количество, целое, не больше остатка. */
  qty: number;
  /**
   * Цена за штуку, предложенная покупателем (решение 18). null — торга нет.
   *
   * Это единственная цена, которую сервер принимает от браузера, и она
   * не подменяет прайс: обе сохраняются рядом, решение принимает продавец.
   */
  offeredPrice?: number | null;
};

/**
 * Тело запроса POST /api/orders.
 *
 * Цены в запросе нет намеренно: сервер берёт её по id из таблицы,
 * клиентское значение игнорируется (technical-spec.md §6).
 */
export type OrderDraft = {
  /** Телефон покупателя. Обязателен: без него в логе заказа нет контакта (решение 2). */
  phone: string;
  items: OrderDraftItem[];
  /**
   * Сумма за весь заказ, предложенная покупателем (решение 18).
   * Перекрывает построчные предложения при подсчёте итога; сами построчные
   * при этом сохраняются — видно, с чего покупатель отталкивался.
   */
  offeredTotal?: number | null;
  /** Комментарий к заказу (решение 18.1). Необязателен, пустой не сохраняется. */
  comment?: string | null;
};

/** Позиция подтверждённого заказа с ценой, зафиксированной сервером. */
export type OrderLine = {
  id: number;
  title: string;
  article: string | null;
  qty: number;
  /** Цена за штуку по прайсу на момент заказа, целые тенге. */
  price: number;
  /** Цена за штуку, предложенная покупателем (решение 18). null — торга нет. */
  offeredPrice: number | null;
  /** Действующая цена × qty: предложенная, если она есть, иначе прайсовая. */
  sum: number;
};

/** Ответ POST /api/orders после успешной записи в лист «Заказы». */
export type OrderResult = {
  /** Номер вида ШКВ-0001 (решение 4). */
  orderNo: string;
  total: number;
  /** Готовая ссылка в WhatsApp с текстом по решению 12. Собирается в lib/whatsapp.ts. */
  whatsappUrl: string;
};

/** Заказ целиком — для бланка печати и админки. */
export type Order = {
  orderNo: string;
  /** ISO 8601 с часовым поясом Уральска. */
  createdAt: string;
  phone: string;
  lines: OrderLine[];
  /** Действующий итог: сумма за заказ от покупателя, если она есть (решение 18). */
  total: number;
  /** Предложение покупателя за весь заказ. null — торга за заказ нет. */
  offeredTotal: number | null;
  /**
   * Комментарий покупателя (решение 18.1). Пустая строка — комментария нет.
   * Необязательное поле: заказы, собранные до его появления, его не имеют.
   */
  comment?: string;
  /** При создании всегда «новый» (data-model.md §8). */
  status: string;
};
