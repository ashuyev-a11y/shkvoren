/**
 * Типы позиции каталога — контракт из docs/data-model.md §9.
 *
 * PublicPart — то, что разрешено отдавать в браузер.
 * AdminPart  — то же плюс поля, которые наружу не уходят (решение 5).
 */

/** Марки, показываемые в MVP (решение 7). */
export type Brand = 'ГАЗ' | 'УАЗ';

/**
 * Вид значения в колонке «Артикул». В данных это не всегда каталожный номер:
 * 24 позиции из 185 содержат размер вида 42x68x16.4 (data-model.md §5).
 */
export type ArticleKind =
  /** Каталожный номер: 4693501070, 0469-00-1602558-00 */
  | 'number'
  /** Размер сальника или подшипника: 42x68x16.4 */
  | 'size'
  /** Артикула нет — 93 позиции из 278 */
  | 'none';

/** Позиция каталога в том виде, в котором уходит в браузер. */
export type PublicPart = {
  /** Колонка ID таблицы. Сквозной ключ, не переиспользуется (data-model.md §3). */
  id: number;
  /** Наименование, приведённое trim. Регистр источника сохранён. */
  title: string;
  /** Значение колонки «Артикул» как есть. null — если пусто. */
  article: string | null;
  articleKind: ArticleKind;
  /** Строка применимости как есть, только trim (решение 10). */
  fitment: string | null;
  /** Марки, найденные в fitment подстрокой. Пустой массив — марка не определена. */
  brands: Brand[];
  /** Категория из данных, одна из восьми (data-model.md §4). */
  category: string;
  /** Цена продажи, целые тенге. */
  price: number;
  /** Остаток, целые штуки. Показываем числом (решение 8). */
  qty: number;
};

/**
 * Позиция со служебными полями. Существует только на сервере и в админке.
 * Ни одно из полей ниже не сериализуется в публичный ответ.
 */
export type AdminPart = PublicPart & {
  /** Номер строки листа — чтобы оператор нашёл позицию в таблице. */
  row: number;
  /** Нормализованный артикул для поиска (data-model.md §5). */
  articleNorm: string;
  /** Закупочная цена, колонка G. В снимке пуста у всех 278 позиций. */
  costPrice: number | null;
  /** Средняя цена рынка, колонка AC. Заполнена у 2 позиций. */
  marketPrice: number | null;
  /** Отклонение текущей цены от рынка, колонка AG. */
  marketDelta: number | null;
  /** Заметка по ценам, колонка AH. Заполнена у 3 позиций. */
  priceNote: string | null;
};

/** Уровень проблемы, найденной при чтении таблицы. */
export type SheetIssueLevel =
  /** Позиция не попадает на витрину. */
  | 'error'
  /** Позиция показывается, но оператору стоит проверить данные. */
  | 'warning';

/** Проблема строки или листа целиком (technical-spec.md §5). */
export type SheetIssue = {
  level: SheetIssueLevel;
  /** Номер строки листа. 0 — проблема относится к листу целиком. */
  row: number;
  /** Причина, текстом для админки. */
  reason: string;
};

/** Результат чтения листа «Запчасти». */
export type PartsRead = {
  parts: AdminPart[];
  issues: SheetIssue[];
  /** Момент чтения из таблицы, для плашки «Данные могли устареть». */
  readAt: string;
};
